#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════
# OpportunitiesZA — Termux Deploy & Maintenance Script
# Make executable: chmod +x deploy.sh      Run: ./deploy.sh
#
# Safety rules this script follows (see docs/ for why):
#   * Works in the folder the script lives in (override: PROJECT_DIR=...).
#   * Runs the project's own validators + sitemap regeneration BEFORE any
#     commit, so CI ("Quality Gates") does not fail after you push.
#   * Never `git add .` — tracked changes only, new files only after you
#     confirm them, crawler logs/outputs/reports always excluded.
#   * Pushes only from $BRANCH, rebases on the remote first, never forces.
#   * User input is passed to Node through environment variables, never
#     pasted into code, so quotes/backslashes in a title cannot break or
#     inject anything.
#   * Never deletes .git or rewrites history.
# ═══════════════════════════════════════════════════════════════

set -uo pipefail

# ── CONFIG ────────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="${PROJECT_DIR:-$SCRIPT_DIR}"
REPO_URL="https://github.com/Ituthema/seta-careers-platform.git"
BRANCH="${BRANCH:-main}"
DATA_FILE="data/opportunities.json"

# Paths that are generated by the crawler / audits and must not be
# committed by a quick publish.
EXCLUDES=(':(exclude)crawler/logs' ':(exclude)crawler/output' ':(exclude)reports' ':(exclude)logs')

GREEN=$'\033[0;32m'; AMBER=$'\033[0;33m'; RED=$'\033[0;31m'
CYAN=$'\033[0;36m';  WHITE=$'\033[1;37m'; RESET=$'\033[0m'

say()  { printf '%s\n' "$*"; }
ok()   { printf '%s%s%s\n' "$GREEN" "$*" "$RESET"; }
warn() { printf '%s%s%s\n' "$AMBER" "$*" "$RESET"; }
info() { printf '%s%s%s\n' "$CYAN"  "$*" "$RESET"; }
die()  { printf '%s❌ %s%s\n' "$RED" "$*" "$RESET" >&2; exit 1; }

ask_yn() { # ask_yn "question" -> returns 0 only for explicit y/Y (default NO)
  local reply
  read -r -p "$1 (y/N): " reply
  [[ "$reply" =~ ^[Yy]$ ]]
}

# ── PRE-FLIGHT ────────────────────────────────────────────────
[ -d "$PROJECT_DIR" ] || die "Project directory not found: $PROJECT_DIR (set PROJECT_DIR=...)"
cd "$PROJECT_DIR" || die "Cannot enter $PROJECT_DIR"

need_repo() { git rev-parse --is-inside-work-tree >/dev/null 2>&1 || die "$PROJECT_DIR is not a git repository (use option 8)."; }
need_node() { command -v node >/dev/null 2>&1 || die "Node.js is not installed. Run: pkg install nodejs"; }

# Validate content, regenerate sitemap, validate routes. Same checks as CI.
run_checks() {
  need_node
  info "Running content validation..."
  node scripts/validate-content.js || return 1
  info "Regenerating sitemap.xml..."
  node sitemap-generator.js >/dev/null || return 1
  info "Validating sitemap/router/data consistency..."
  node validate-content.js || return 1
  ok "✅ Checks passed."
}

# Refuse to push from the wrong branch.
need_branch() {
  local current
  current="$(git rev-parse --abbrev-ref HEAD)"
  [ "$current" = "$BRANCH" ] || die "You are on '$current' but this script pushes '$BRANCH'. Run: git checkout $BRANCH"
}

# commit_and_push "message"  — commits what is ALREADY STAGED, then pushes.
commit_and_push() {
  need_branch
  if git diff --cached --quiet; then
    warn "ℹ️  Nothing staged — nothing to commit."
    return 0
  fi
  git commit -m "$1" || die "Commit failed."
  info "Syncing with GitHub (rebase, no force)..."
  # --autostash: excluded files (reports/, crawler output) may be modified but
  # uncommitted; without it git refuses to rebase and the error looks like a conflict.
  if ! git pull --rebase --autostash origin "$BRANCH"; then
    if [ -d "$(git rev-parse --git-path rebase-merge)" ] || [ -d "$(git rev-parse --git-path rebase-apply)" ]; then
      die "Rebase hit a conflict. Run 'git rebase --abort' to go back, then fix by hand. Nothing was pushed (your commit is saved locally)."
    fi
    die "Could not sync with GitHub (network, or the remote branch is missing). Nothing was pushed; your commit is saved locally."
  fi
  info "Pushing to GitHub..."
  if git push origin "$BRANCH"; then
    ok "✅ Pushed successfully! Site updates in 1–5 minutes."
    say "   Check: https://github.com/Ituthema/seta-careers-platform/actions"
  else
    die "Push failed. Check your connection or GitHub token. Your commit is saved locally."
  fi
}

# ── HEADER + MENU ─────────────────────────────────────────────
clear 2>/dev/null || true
echo ""
echo "${GREEN}╔══════════════════════════════════════════════════════╗${RESET}"
echo "${GREEN}║${WHITE}  🧭 OpportunitiesZA — Deploy & Maintenance Script    ${GREEN}║${RESET}"
echo "${GREEN}╚══════════════════════════════════════════════════════╝${RESET}"
info "📁 Working directory: $PROJECT_DIR   (branch: $BRANCH)"
echo ""
echo "${WHITE}What would you like to do?${RESET}"
echo ""
echo "  1) 🚀 Quick publish (validate, review, commit, push)"
echo "  2) 📝 Add new opportunity (guided)"
echo "  3) ✅ Validate content"
echo "  4) 🗑️  Mark expired opportunities"
echo "  5) 🗺️  Regenerate sitemap.xml"
echo "  6) 📊 Show project stats"
echo "  7) 🔄 Pull latest from GitHub"
echo "  8) 🏗️  Initial setup (first time)"
echo "  9) ❌ Exit"
echo ""
read -r -p "Enter choice [1-9]: " choice
echo ""

case "$choice" in

# ── 1. QUICK PUBLISH ─────────────────────────────────────────
1)
  need_repo; need_branch
  info "🚀 Quick Publish"
  if [ -z "$(git status --porcelain)" ]; then
    warn "ℹ️  Nothing to commit — working tree is clean."; exit 0
  fi

  run_checks || die "Checks failed. Fix the errors above, then run again. Nothing was committed."

  # Tracked changes only; crawler output and reports are excluded.
  git add -u -- . "${EXCLUDES[@]}"
  # sitemap.xml may have just been regenerated.
  [ -f sitemap.xml ] && git add -- sitemap.xml

  untracked="$(git ls-files --others --exclude-standard -- . "${EXCLUDES[@]}")"
  if [ -n "$untracked" ]; then
    warn "New (untracked) files found:"
    printf '%s\n' "$untracked" | sed 's/^/    /'
    if ask_yn "Include these new files?"; then
      printf '%s\n' "$untracked" | while IFS= read -r f; do git add -- "$f"; done
    fi
  fi

  echo ""
  warn "Staged for commit:"
  git diff --cached --stat
  if git diff --cached --quiet; then warn "Nothing staged."; exit 0; fi
  echo ""
  ask_yn "Commit and push these changes?" || { warn "Cancelled — nothing committed (changes stay staged)."; exit 0; }

  read -r -p "Commit message (Enter for auto): " msg
  [ -n "$msg" ] || msg="Content update $(date '+%Y-%m-%d %H:%M')"
  commit_and_push "$msg"
  ;;

# ── 2. ADD NEW OPPORTUNITY ────────────────────────────────────
2)
  need_repo; need_node; need_branch
  info "📝 Add New Opportunity"
  [ -f "$DATA_FILE" ] || die "$DATA_FILE not found."
  git diff --quiet -- "$DATA_FILE" || die "$DATA_FILE has uncommitted changes. Commit or discard them first."

  read -r -p "Title: " A_TITLE
  read -r -p "Category (learnership/internship/bursary/apprenticeship/tvet): " A_CAT
  read -r -p "Sector (e.g. EWSETA, Banking, Retail): " A_SECTOR
  read -r -p "Province (Nationwide/Gauteng/Western Cape/KwaZulu-Natal/Eastern Cape/Limpopo/Mpumalanga/North West/Free State/Northern Cape): " A_PROV
  read -r -p "Qualification (Matric/Diploma/Degree): " A_QUAL
  read -r -p "Stipend: " A_STIPEND
  read -r -p "Closing date (YYYY-MM-DD): " A_CLOSE
  read -r -p "Application URL: " A_URL
  read -r -p "Source name: " A_SRCNAME
  read -r -p "Source URL: " A_SRCURL
  read -r -p "Description (1-2 sentences): " A_DESC
  read -r -p "Who may apply (comma list: unemployed,student,employed): " A_EMP
  read -r -p "Tags (comma-separated, e.g. matric,gauteng): " A_TAGS
  A_VERIFIED=false
  ask_yn "Have YOU checked the source page yourself and want it marked 'source checked'?" && A_VERIFIED=true

  BACKUP="$(mktemp)"; cp "$DATA_FILE" "$BACKUP"
  export A_TITLE A_CAT A_SECTOR A_PROV A_QUAL A_STIPEND A_CLOSE A_URL A_SRCNAME A_SRCURL A_DESC A_EMP A_TAGS A_VERIFIED DATA_FILE

  if node - <<'NODE'
const fs = require('fs');
const e = process.env;
const CATS = ['learnership','internship','bursary','apprenticeship','tvet'];
const PROVS = ['Eastern Cape','Free State','Gauteng','KwaZulu-Natal','Limpopo','Mpumalanga','Northern Cape','North West','Western Cape','Nationwide'];
const EMP = ['unemployed','student','employed'];
const fail = (m) => { console.error('❌ ' + m); process.exit(1); };
const need = (k, label) => { if (!(e[k] || '').trim()) fail(label + ' is required.'); return e[k].trim(); };
const url = (k, label) => { const v = need(k, label); try { if (!/^https?:$/.test(new URL(v).protocol)) throw 0; } catch { fail(label + ' must be a full http(s) URL.'); } return v; };

const title = need('A_TITLE', 'Title');
const category = need('A_CAT', 'Category').toLowerCase(); if (!CATS.includes(category)) fail('Category must be one of: ' + CATS.join(', '));
const province = need('A_PROV', 'Province'); if (!PROVS.includes(province)) fail('Province must be one of: ' + PROVS.join(', '));
const close = need('A_CLOSE', 'Closing date');
if (!/^\d{4}-\d{2}-\d{2}$/.test(close) || new Date(close + 'T00:00:00Z').toISOString().slice(0, 10) !== close) fail('Closing date must be a real date as YYYY-MM-DD.');
const qual = need('A_QUAL', 'Qualification');
const employment = need('A_EMP', 'Who may apply').split(',').map(s => s.trim().toLowerCase()).filter(Boolean);
if (!employment.length || employment.some(s => !EMP.includes(s))) fail('Who may apply must use only: ' + EMP.join(', '));
const tags = (e.A_TAGS || '').split(',').map(s => s.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')).filter(Boolean);

const data = JSON.parse(fs.readFileSync(e.DATA_FILE, 'utf8'));
const maxId = data.reduce((m, o) => Math.max(m, parseInt(o.id, 10) || 0), 0);
const id = String(maxId + 1).padStart(3, '0');
let slug = title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
if (!slug) fail('Title must contain letters or numbers.');
if (data.some(o => o.slug === slug)) fail('An opportunity with slug "' + slug + '" already exists.');
const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Johannesburg' }).format(new Date());

data.unshift({
  id, slug, title, category,
  sector: need('A_SECTOR', 'Sector'),
  province, qualification_level: qual,
  stipend: need('A_STIPEND', 'Stipend'),
  closing_date: close,
  application_url: url('A_URL', 'Application URL'),
  source_name: need('A_SRCNAME', 'Source name'),
  source_url: url('A_SRCURL', 'Source URL'),
  verified: e.A_VERIFIED === 'true',
  featured: false,
  expired: false,
  description: need('A_DESC', 'Description'),
  eligibility: ['South African citizen with valid ID', qual + ' certificate'],
  employment_eligibility: employment,
  documents_needed: ['Certified copy of ID', 'Certified copy of ' + qual + ' certificate', 'CV', 'Motivational letter'],
  tags,
  posted_date: today,
  updated_date: today,
});
fs.writeFileSync(e.DATA_FILE, JSON.stringify(data, null, 2) + '\n');
console.log('Prepared record ' + id + ' (' + slug + ').');
NODE
  then
    if run_checks; then
      git add -- "$DATA_FILE" sitemap.xml
      git diff --cached -- "$DATA_FILE" | head -60
      if ask_yn "Commit and push this new opportunity?"; then
        commit_and_push "Add opportunity: $A_TITLE (closes $A_CLOSE)"
      else
        warn "Cancelled — restoring files."; git reset -q -- "$DATA_FILE" sitemap.xml; cp "$BACKUP" "$DATA_FILE"; git checkout -q -- sitemap.xml
      fi
    else
      warn "Validation failed — restoring $DATA_FILE."; cp "$BACKUP" "$DATA_FILE"; git checkout -q -- sitemap.xml 2>/dev/null
      die "Nothing was added. Fix the problem above and try again."
    fi
  else
    cp "$BACKUP" "$DATA_FILE"
    die "Nothing was added."
  fi
  rm -f "$BACKUP"
  ;;

# ── 3. VALIDATE ──────────────────────────────────────────────
3)
  need_node
  info "✅ Validating content..."
  node -e '
    const fs=require("fs"); let bad=0;
    for (const f of fs.readdirSync("data").filter(n=>n.endsWith(".json"))) {
      try { const d=JSON.parse(fs.readFileSync("data/"+f,"utf8")); console.log("  ✅ data/"+f+" — valid ("+(Array.isArray(d)?d.length+" records":"object")+")"); }
      catch(e){ console.log("  ❌ data/"+f+" — INVALID JSON: "+e.message); bad++; }
    }
    process.exit(bad?1:0);' || die "Fix the invalid JSON above."
  run_checks || die "Content validation failed."
  ;;

# ── 4. MARK EXPIRED ──────────────────────────────────────────
4)
  need_repo; need_node; need_branch
  info "🗑️  Mark expired opportunities (closing date already passed)"
  git diff --quiet -- "$DATA_FILE" || die "$DATA_FILE has uncommitted changes. Commit or discard them first."
  node scripts/mark-expired.js --dry-run || die "Could not check for lapsed listings."
  echo ""
  ask_yn "Mark the listings above as expired?" || { warn "Cancelled."; exit 0; }
  node scripts/mark-expired.js || die "mark-expired failed."
  run_checks || die "Checks failed after marking expired. Run: git checkout -- $DATA_FILE sitemap.xml"
  git add -- "$DATA_FILE" sitemap.xml
  git diff --cached --stat
  ask_yn "Commit and push?" && commit_and_push "Mark lapsed opportunities as expired" || warn "Left staged, not pushed."
  ;;

# ── 5. REGENERATE SITEMAP ─────────────────────────────────────
5)
  need_repo; need_node; need_branch
  info "🗺️  Regenerating sitemap.xml..."
  run_checks || die "Checks failed."
  if git diff --quiet -- sitemap.xml; then ok "sitemap.xml is already up to date."; exit 0; fi
  git add -- sitemap.xml
  ask_yn "Commit and push the updated sitemap?" && commit_and_push "Update sitemap $(date '+%Y-%m-%d')" || warn "Left staged, not pushed."
  ;;

# ── 6. PROJECT STATS ──────────────────────────────────────────
6)
  need_node
  info "📊 Project Statistics"
  node -e '
    const fs=require("fs");
    const today=new Intl.DateTimeFormat("en-CA",{timeZone:"Africa/Johannesburg"}).format(new Date());
    const o=JSON.parse(fs.readFileSync("data/opportunities.json","utf8"));
    const live=o.filter(x=>!x.expired);
    const days=x=>Math.round((new Date(x.closing_date)-new Date(today))/864e5);
    const by={}; live.forEach(x=>by[x.category]=(by[x.category]||0)+1);
    console.log("  Total opportunities:   "+o.length);
    console.log("  Live (not expired):    "+live.length);
    console.log("  Expired:               "+(o.length-live.length));
    console.log("  Closing within 30 days:"+live.filter(x=>days(x)>=0&&days(x)<=30).length);
    console.log("  Lapsed but still live: "+live.filter(x=>days(x)<0).length+"  (run option 4)");
    console.log("  Newest updated_date:   "+o.map(x=>x.updated_date).filter(Boolean).sort().pop());
    console.log("\n  By category:"); Object.keys(by).sort().forEach(k=>console.log("    "+k+": "+by[k]));
    try{console.log("\n  Guide articles:        "+JSON.parse(fs.readFileSync("data/guides.json","utf8")).length);}catch{}
  '
  echo ""
  if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    say "  Recent commits:"; git log --oneline -5 | sed 's/^/    /'
  fi
  ;;

# ── 7. PULL LATEST ────────────────────────────────────────────
7)
  need_repo; need_branch
  info "🔄 Pulling latest changes from GitHub (fast-forward only)..."
  git fetch origin || die "Fetch failed."
  git pull --ff-only origin "$BRANCH" || die "Cannot fast-forward (local commits or changes diverge). Resolve by hand; nothing was overwritten."
  ok "✅ Up to date with GitHub."
  ;;

# ── 8. INITIAL SETUP ─────────────────────────────────────────
8)
  info "🏗️  Initial Setup"
  if [ -d ".git" ]; then
    die "Git is already set up here. This script will not delete or re-create .git. (To start over, move this folder aside and run: git clone $REPO_URL)"
  fi
  warn "Tip: if the repo already exists on GitHub, 'git clone $REPO_URL' is simpler and safer than this."
  ask_yn "Initialise a new repository in $PROJECT_DIR?" || { warn "Cancelled."; exit 0; }

  git config --global --get-all safe.directory | grep -qxF "$PROJECT_DIR" || git config --global --add safe.directory "$PROJECT_DIR"
  git init -b "$BRANCH" || die "git init failed."
  git add -- . "${EXCLUDES[@]}"
  warn "Files that will be in the first commit:"; git status --short | head -40
  ask_yn "Create the first commit with these files?" || { warn "Cancelled (repo initialised, nothing committed)."; exit 0; }
  git commit -m "Initial deployment — OpportunitiesZA $(date '+%Y-%m-%d')" || die "Commit failed."

  read -r -p "GitHub repository URL [$REPO_URL]: " repo_url
  repo_url="${repo_url:-$REPO_URL}"
  git remote add origin "$repo_url" || die "Could not add remote."
  warn "You'll be prompted for your GitHub username and Personal Access Token."
  git push -u origin "$BRANCH" || die "Push failed."
  ok "✅ Initial push complete! Enable GitHub Pages: Repository → Settings → Pages → $BRANCH branch"
  ;;

9) warn "Goodbye! 🧭"; exit 0 ;;
*) die "Invalid choice. Run the script again." ;;
esac

echo ""
ok "═══ Done — OpportunitiesZA Deploy Script ═══"
